using System;

namespace HelloWorld
{
  class Program
  {
    static void Main(string[] args)
    {
      Console.WriteLine("Hello World 123!");    
    }
  }
}

// using System means that we can use classes from the System namespace

// namespace is used to organize your code, and it is a container for classes and other namespaces

// class is a container for data and methods, 
// Every line of code that runs in C# must be inside a class. In our example, we named the class Program

// Console is a class of the System namespace
// System.Console.WriteLine() to print/output text , we can write --> Console.WriteLine()


